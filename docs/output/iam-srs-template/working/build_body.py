h("2.2 存量用户加入目标用户组（对应需求编号 202611JSIAM02）", 2)

h("2.2.1 需求背景和目标（必须）", 3)
lead("需求背景：", "权限迁移不能一步到位地“先退旧组”。旧组权限在解绑后立即失效，若此时新组关系尚未建立，用户会在窗口内同时不具备新旧两组权限（即权限空档），直接影响业务连续性。因此迁移必须“先加后减”：先把用户加入目标新用户组，使权限只增不减，再执行退出旧组。目标组的权限策略由权限管理流程预先配置完成，本功能点只负责建立“用户—目标组”的成员关系。")
lead("需求目标：", "对清单内用户批量建立与目标用户组的成员关系，单用户粒度可独立重试；重复执行不产生重复关系、不报错；为后续“退出旧组”提供前置条件，并保证整个过程中用户至少拥有目标组的权限。")
lead("目标用户：", "云平台运维团队（迁移执行人）。")

h("2.2.2 功能需求", 3)
h("2.2.2.1 功能的使用场景", 4)
para("在迁移窗口内，运维人员对已通过校验与审批的清单执行正式迁移。工具按清单逐条为用户建立目标组成员关系，并即时输出每一条的处理结果。绑定成功后用户立即获得目标组的权限，同时其原有的旧组权限仍然保留，业务不中断。若某用户绑定失败，该用户保持迁移前的权限状态，等待人工处理或续跑，不影响其余用户继续执行。")

h("2.2.2.2 UI界面（非必须）", 4)
