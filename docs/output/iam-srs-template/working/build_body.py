h("2 产品功能", 1)

para("本需求交付一项存量用户组迁移能力，交付形态为运维侧迁移工具（配置文件 + 命令行执行 + 结构化执行记录），不面向业务用户提供操作入口。迁移在华为云 IAM 身份中心的成员关系层面完成：业务侧已完成接口可行性验证，只需 4 个开放接口，即可拆分为“用户加入目标组”与“用户退出旧组”两个相互独立的写操作。")
para("权限收敛的必要性在于：现有存量用户的权限通过旧用户组继承获得，其中包含业务上已不再需要的权限（例如对象存储的列举类权限）。仅把用户加入新组并不会自动剥离旧组权限，必须显式解除旧组成员关系，收敛才真正生效；而在解除之前必须先建立新组关系，否则用户会在迁移窗口内失去全部权限。因此这项能力由四个功能点协同完成，执行顺序固定为“先加入新组、再退出旧组”。")
para("本需求包含以下四个功能点：")
steps([
    "存量用户组迁移任务配置与校验：固化身份源、旧组、目标组、调用凭据与待迁移用户清单，并在任何写操作之前完成校验与目标组解析；",
    "存量用户加入目标用户组：对清单内用户批量建立目标组（Membership）关系，保证用户权限只增不减；",
    "存量用户退出原用户组：定位并解除用户与旧用户组的成员关系，完成权限收敛；",
    "迁移任务编排、执行留痕与断点续跑：保证执行顺序、失败隔离、逐用户留痕、结果汇总与中断续跑。",
])
para("本次不包含以下内容：目标用户组的创建与权限策略配置（作为迁移前置条件，由权限管理流程预先完成）；用户开户与身份源创建；迁移结果的自动校验抽查（不调用成员关系校验类接口）；图形化操作界面；失败用户的自动回滚（仅提供重试与人工回退说明）。")

